"""Generate the APWorld and mod data tables from the mod's debug dump.

Inputs:  data/dump/jobs_raw.json, names.json (copied from Mods/PowerwashSim2AP/dump, debug.txt = 4 or 5)
         data/categories.json (hand-sorted D1 categories, keyed by job unique name)
Outputs: apworld/powerwashsimulator2/Data.py, mod/Resources/ap_data.json

Run: python3 apworld/gen_data.py
"""
import json
import pprint
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
dump_dir = root / "data" / "dump"
raw_jobs = json.loads((dump_dir / "jobs_raw.json").read_text())
names = json.loads((dump_dir / "names.json").read_text())
categories = json.loads((root / "data" / "categories.json").read_text())

# Removals Van is the first career job; the campaign's TutorialJobId is 0 in the dump, so it can't be read from there
FIRST_JOB = "REMOVALVAN"


def display_name(unique_name: str) -> str:
    """Localized name, or the unique name in title case when localization failed or returned a key."""
    name = names.get(unique_name) or ""
    if not name or name.startswith("<") or re.fullmatch(r"[A-Z0-9_]+", name):
        return unique_name.replace("_", " ").title()
    return name


jobs = {}
for job in raw_jobs["jobs"]:
    unique_name = job["unique_name"]
    if unique_name not in categories:
        raise SystemExit(f"{unique_name} has no category in data/categories.json")
    name = display_name(unique_name)
    if name in jobs:
        raise SystemExit(f"duplicate job name {name!r}: {jobs[name]['unique_name']} and {unique_name}")
    # PWS1 naming: component (= WashTarget GameObject) name with "_" shown as " "
    objects = [component["name"].replace("_", " ")
               for stage in job["stages"] for task in stage["tasks"] for component in task["components"]]
    if len(set(objects)) != len(objects):
        raise SystemExit(f"{unique_name} has duplicate object names")
    jobs[name] = {
        "unique_name": unique_name,
        "category": categories[unique_name],
        "stages": len(job["stages"]),
        "bonus_tasks": job["bonus_tasks"],
        "objects": sorted(objects),
    }

first_job = display_name(FIRST_JOB)
out = root / "apworld" / "powerwashsimulator2" / "Data.py"
out.write_text(
    "# Generated by apworld/gen_data.py from data/dump and data/categories.json. Do not edit.\n"
    f"first_job = {first_job!r}\n"
    f"jobs = {pprint.pformat(jobs, width=120, sort_dicts=False)}\n"
)

# the mod maps AP names back to game content with this
mod_data = root / "mod" / "Resources" / "ap_data.json"
mod_data.parent.mkdir(exist_ok=True)
mod_data.write_text(json.dumps({
    "jobs": {name: job["unique_name"] for name, job in jobs.items()},
}, indent=1))

print(f"wrote {out.relative_to(root)} and {mod_data.relative_to(root)}: {len(jobs)} jobs, "
      f"{sum(len(j['objects']) for j in jobs.values())} objects")
